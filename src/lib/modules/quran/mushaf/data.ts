export function paraOfSuraAyah(sura: number, ayah: number): number {
	let para = 1;
	PARA_STARTS.forEach(([s, a], i) => {
		if (sura > s || (sura === s && ayah >= a)) para = i + 1;
	});
	return para;
}

/**
 * Physical mushaf pairing: page 1 opens alone; from page 2 onward pages pair up as
 * (even = right, even + 1 = left), matching how an RTL book actually opens.
 */
export function getSpreadPair(p: number, totalPages: number): { right: number; left: number | null } {
	if (p <= 1) return { right: 1, left: null };
	const right = p % 2 === 0 ? p : p - 1;
	const left = right + 1;
	return { right, left: left <= totalPages ? left : null };
}

